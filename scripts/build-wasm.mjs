#!/usr/bin/env node
/**
 * Build the Rust/WASM runtime and the drop-in ES module bundles.
 *
 *   1. wasm-pack build (release, --target web) -> src/wasm/generated/pkg
 *      (wasm-pack runs its bundled wasm-opt with the flags from Cargo.toml)
 *   2. optional extra pass with a system `wasm-opt`
 *   3. patch the glue so it never touches `import.meta.url` (the inline build
 *      always passes the module explicitly; Jest cannot parse import.meta)
 *   4. inline the .wasm as base64 -> src/wasm/generated/wasm-inline.js
 *   5. tsup -> dist/wasm/index.mjs (inline) + dist/wasm/split/index.mjs
 *
 * Flags:
 *   --no-bundle   stop after step 4 (used by `npm run test:wasm`)
 */
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const crateDir = path.join(root, "rust", "dim-core");
const generated = path.join(root, "src", "wasm", "generated");
const pkgDir = path.join(generated, "pkg");
const noBundle = process.argv.includes("--no-bundle");

function run(cmd, args, opts = {}) {
  console.log(`> ${cmd} ${args.join(" ")}`);
  execFileSync(cmd, args, { stdio: "inherit", cwd: root, ...opts });
}

function hasCommand(cmd) {
  return spawnSync(cmd, ["--version"], { stdio: "ignore" }).status === 0;
}

if (!hasCommand("wasm-pack")) {
  console.error(
    "wasm-pack is required: https://rustwasm.github.io/wasm-pack/installer/",
  );
  process.exit(1);
}

fs.rmSync(pkgDir, { recursive: true, force: true });
run("wasm-pack", [
  "build",
  crateDir,
  "--release",
  "--target",
  "web",
  "--no-pack",
  "--out-name",
  "dim_core",
  "--out-dir",
  pkgDir,
]);

const wasmPath = path.join(pkgDir, "dim_core_bg.wasm");
if (hasCommand("wasm-opt")) {
  run("wasm-opt", ["-Oz", "--strip-debug", "--strip-producers", "-o", wasmPath, wasmPath]);
} else {
  console.log("system wasm-opt not found; using wasm-pack's optimisation only");
}

const gluePath = path.join(pkgDir, "dim_core.js");
let glue = fs.readFileSync(gluePath, "utf8");
const patched = glue.replace(
  /new URL\(\s*['"]dim_core_bg\.wasm['"]\s*,\s*import\.meta\.url\s*\)/g,
  '(() => { throw new Error("dim-core: pass the wasm module or URL explicitly"); })()',
);
if (patched.includes("import.meta")) {
  throw new Error("dim-core glue still references import.meta; update the patch");
}
fs.writeFileSync(gluePath, patched);
fs.rmSync(path.join(pkgDir, ".gitignore"), { force: true });

const bytes = fs.readFileSync(wasmPath);
fs.writeFileSync(
  path.join(generated, "wasm-inline.js"),
  `// Generated by scripts/build-wasm.mjs. Do not edit.\nexport const wasmBase64 = "${bytes.toString("base64")}";\n`,
);
console.log(
  `dim-core.wasm: ${(bytes.length / 1024).toFixed(1)} KiB (${((bytes.length * 4) / 3 / 1024).toFixed(1)} KiB base64)`,
);

if (noBundle) process.exit(0);

run("npx", ["tsup", "--config", "tsup.wasm.config.ts"]);

const distWasm = path.join(root, "dist", "wasm");
fs.copyFileSync(wasmPath, path.join(distWasm, "split", "dim_core_bg.wasm"));
fs.writeFileSync(path.join(distWasm, "index.d.ts"), 'export * from "../index";\n');
fs.writeFileSync(
  path.join(distWasm, "split", "index.d.ts"),
  'export * from "../../index";\n',
);
console.log("dist/wasm ready");
